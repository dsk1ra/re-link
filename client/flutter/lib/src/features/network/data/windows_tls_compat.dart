SecurityContext? _windowsSecurityContext;

/// System trust store plus the bundled ISRG Root X1. Strict validation only.
SecurityContext createSecurityContextWithBundledRoots() {
  final context = SecurityContext(withTrustedRoots: true);
  try {
    context.setTrustedCertificatesBytes(utf8.encode(isrgRootX1Pem));
  } on TlsException {
    // Root already present in the platform store.
  }
  return context;
}

HttpClient? _createWindowsHttpClient(Uri? uri) {
  if (uri == null || !Platform.isWindows) return null;
  if (uri.scheme != 'https' && uri.scheme != 'wss') return null;
  _windowsSecurityContext ??= createSecurityContextWithBundledRoots();
  return HttpClient(context: _windowsSecurityContext);
}

http.Client createPlatformHttpClientForBaseUrl(String baseUrl) {
  final client = _createWindowsHttpClient(Uri.tryParse(baseUrl));
  return client == null ? http.Client() : IOClient(client);
}

IOWebSocketChannel connectPlatformWebSocket(String wsUrl) {
  final uri = Uri.parse(wsUrl);
  final client = _createWindowsHttpClient(uri);
  if (client == null) {
    return IOWebSocketChannel.connect(uri);
  }
  return IOWebSocketChannel.connect(uri, customClient: client);
}
